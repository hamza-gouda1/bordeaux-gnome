"""Render templates/*.tmpl with tokens/tokens.toml into themes/<Variant>/.

Usage:
    tools/build.py            # write every generated file
    tools/build.py --check    # exit 1 if committed output differs from a fresh render

Template syntax: ${token} inserts a token; ${token@30} inserts a colour token
at 30% alpha (as rgba()). Unknown tokens and leftover ${...} are errors.
"""

import argparse
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import tokenlib as tl  # noqa: E402

ROOT = tl.ROOT
TEMPLATES = ROOT / "templates"
# template -> output path under themes/<Variant>/
OUTPUTS = {
    "gnome-shell.css.tmpl": "gnome-shell/gnome-shell.css",
    "gtk-3.0.css.tmpl": "gtk-3.0/gtk.css",
    "gtk-4.0.css.tmpl": "gtk-4.0/gtk.css",
}
HEADER = (
    "/* Generated by tools/build.py from tokens/tokens.toml, do not edit. */\n"
    "/* SPDX-License-Identifier: GPL-3.0-or-later */\n"
)
REF = re.compile(r"\$\{([A-Za-z0-9_-]+)(?:@(\d+(?:\.\d+)?))?\}")


def render(text, toks, where):
    def sub(m):
        name, alpha = m.group(1), m.group(2)
        if name not in toks:
            raise SystemExit(f"{where}: unknown token ${{{name}}}")
        value = str(toks[name])
        if alpha is None:
            return value
        c = tl.parse_color(value)
        if c is None:
            raise SystemExit(f"{where}: ${{{name}@{alpha}}} is not a colour token")
        return tl.rgba(c, float(alpha) / 100)

    out = REF.sub(sub, text)
    if "${" in out:
        raise SystemExit(f"{where}: unresolved ${{...}} after render")
    return out


# Fixed GNOME Terminal profile UUIDs, one per variant (never change these:
# uninstall finds the profiles by them).
TERMINAL_UUIDS = {
    "Bordeaux": "9b0d3a10-0b0e-4d11-9a01-000000000001",
    "Oxblood-Noir": "9b0d3a10-0b0e-4d11-9a01-000000000002",
    "Merlot-Day": "9b0d3a10-0b0e-4d11-9a01-000000000003",
}
# Opt-in icon and cursor themes, applied only when already installed.
ICON_THEME = {"dark": "Papirus-Dark", "light": "Papirus"}
CURSOR_THEME = {"dark": "DMZ-Black", "light": "DMZ-White"}
BLUR_BRIGHTNESS = {"dark": 0.75, "light": 0.95}  # effect brightness
HASH_HEADER = (
    "# Generated by tools/build.py from tokens/tokens.toml, do not edit.\n"
    "# SPDX-License-Identifier: GPL-3.0-or-later\n"
)


def hexc(c):
    return "#{:02x}{:02x}{:02x}".format(*(round(v) for v in c[:3]))


def gv_str(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def render_preset(toks):
    """Lines of `group schema key gvariant`; group is core, icons or cursor."""
    scheme = toks["scheme"]
    blur = "org.gnome.shell.extensions.blur-my-shell"
    dock = "org.gnome.shell.extensions.dash-to-dock"
    ui = "org.gnome.desktop.interface"
    bright = BLUR_BRIGHTNESS[scheme]

    def pipe(name, radius):
        return (f"'pipeline_bordeaux_{name}': {{'name': <'Bordeaux {name}'>, 'effects': <[<{{"
                f"'type': <'dual_kawase_blur'>, 'id': <'effect_bordeaux_{name}'>, "
                f"'params': <{{'unscaled_radius': <{radius}>, 'brightness': <{bright}>}}>}}>]>}}")

    pipelines = "{" + pipe("slab", toks["blur-slab"]) + ", " + pipe("island", toks["blur-island"]) + "}"
    rows = [
        ("core", ui, "font-name", gv_str("Geist 11")),
        ("core", ui, "monospace-font-name", gv_str("Geist Mono 11")),
        # Ubuntu Dock on the left, one glass slab that does not span the screen.
        ("core", dock, "dock-position", gv_str("LEFT")),
        ("core", dock, "dash-max-icon-size", "48"),
        ("core", dock, "extend-height", "false"),
        # Intellihide: the dock slides away when a window overlaps it and returns when
        # the pointer touches the screen edge, so apps get the full width.
        ("core", dock, "dock-fixed", "false"),
        ("core", dock, "autohide", "true"),
        ("core", dock, "intellihide", "true"),
        ("core", dock, "intellihide-mode", gv_str("ALL_WINDOWS")),
        # Pressure barrier, not dwell: dwell (require-pressure false) only fires when the
        # pointer rests at exactly x == monitor.x for show-delay without the focused
        # window's user_time changing, and only once per entry (docking.js _checkDockDwell).
        # The barrier spans the whole work-area edge and also catches a quick flick.
        # show-delay is the pressure time window, so it must not be tiny.
        ("core", dock, "require-pressure-to-show", "true"),
        ("core", dock, "pressure-threshold", "30.0"),
        ("core", dock, "show-delay", "0.25"),
        ("core", dock, "hide-delay", "0.2"),
        ("core", dock, "animation-time", "0.15"),
        # DEFAULT transparency and no custom colour: anything else makes ubuntu-dock
        # set an inline `border-color`/`background-color` on the slab, which beats the
        # theme's border. The glass comes from the theme CSS instead.
        ("core", dock, "transparency-mode", gv_str("DEFAULT")),
        ("core", dock, "custom-background-color", "false"),
        ("core", dock, "apply-custom-theme", "false"),
        # DEFAULT draws round running-app dots (focused one gold via the theme CSS);
        # DASHES draws a bar on the dock's inner edge, which is a gold strip when focused.
        ("core", dock, "running-indicator-style", gv_str("DEFAULT")),
        ("core", ui, "clock-show-weekday", "true"),
        # blur-my-shell (pipeline schema): our two pipelines are merged into the
        # user's existing ones; no panel blur, it would flatten the three capsules.
        ("core", blur, "pipelines", "merge:" + pipelines),
        ("core", blur + ".panel", "blur", "false"),
        # Dock and overview blur are off: they re-blur every frame while windows
        # animate and made Super laggy. The dock slab is a solid colour in the CSS.
        ("core", blur + ".dash-to-dock", "blur", "false"),
        # blur-my-shell's popup component re-skins menus with its own copy of the stock
        # sheet, `!important` and GNOME blue included (Quick Settings tiles, calendar
        # today). Turning its background override off leaves the theme in charge.
        ("core", blur + ".popup", "override-background", "false"),
        # Popup blur (default true) puts a rectangular blur surface behind Quick Settings,
        # notifications and menus. It follows the target's allocation with its own corner
        # radius (quick-settings-corner-radius defaults to 36, ours is r-slab) and shows
        # as a larger dark rectangle around the popup. The slabs are already 0.86-opaque.
        ("core", blur + ".popup", "blur", "false"),
        ("core", blur + ".overview", "blur", "false"),
        ("core", blur + ".lockscreen", "blur", "true"),
        ("core", blur + ".lockscreen", "pipeline", gv_str("pipeline_bordeaux_slab")),
        # Just Perfection: bar height is the island row, animation speed 4 (1 = stock, 8 = fastest).
        ("core", "org.gnome.shell.extensions.just-perfection", "panel-size", toks["panel-h"].removesuffix("px")),
        ("core", "org.gnome.shell.extensions.just-perfection", "animation", "4"),
        # No half-visible neighbouring workspace at the right edge of the overview.
        ("core", "org.gnome.shell.extensions.just-perfection", "workspace-peek", "false"),
        ("icons", ui, "icon-theme", gv_str(ICON_THEME[scheme])),
        ("cursor", ui, "cursor-theme", gv_str(CURSOR_THEME[scheme])),
    ]
    out = HASH_HEADER + "# group schema key value (gvariant text)\n"
    out += "".join(f"{g} {s} {k} {v}\n" for g, s, k, v in rows)
    return out


def render_terminal(toks, uuid):
    pal = ", ".join(gv_str(hexc(tl.parse_color(toks[f"a{i}"]))) for i in range(16))
    cols = lambda name: gv_str(hexc(tl.parse_color(toks[name])))  # noqa: E731
    variant = toks["variant"]
    name = variant if variant.startswith("Bordeaux") else f"Bordeaux {variant}"
    kv = [
        ("visible-name", gv_str(name)),
        ("use-theme-colors", "false"),
        ("use-theme-transparency", "false"),
        ("use-transparent-background", "false"),
        ("foreground-color", cols("term-fg")),
        ("background-color", cols("term-bg")),
        ("bold-color-same-as-fg", "true"),
        ("cursor-colors-set", "true"),
        ("cursor-background-color", cols("gold")),
        ("cursor-foreground-color", cols("term-bg")),
        ("highlight-colors-set", "true"),
        ("highlight-background-color", cols("sel")),
        ("highlight-foreground-color", cols("fg-0")),
        ("palette", f"[{pal}]"),
        ("use-system-font", "false"),
        ("font", gv_str("Geist Mono 11")),
    ]
    out = HASH_HEADER + "# dconf dump of /org/gnome/terminal/legacy/profiles:/\n"
    out += f"[:{uuid}]\n" + "".join(f"{k}={v}\n" for k, v in kv)
    return out


def render_all():
    data = tl.load()
    files = {}
    for variant in data["variant"]:
        toks = tl.variant_tokens(data, variant)
        for tmpl, out in OUTPUTS.items():
            src = TEMPLATES / tmpl
            body = render(src.read_text(), toks, f"{tmpl} [{variant}]")
            files[pathlib.Path("themes") / variant / out] = HEADER + body
        files[pathlib.Path("presets") / f"{variant}.preset"] = render_preset(toks)
        files[pathlib.Path("terminal") / f"{variant}.dconf"] = render_terminal(toks, TERMINAL_UUIDS[variant])
    return files


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if output is stale")
    args = ap.parse_args()

    files = render_all()
    stale = []
    for rel, text in files.items():
        path = ROOT / rel
        if args.check:
            if not path.is_file() or path.read_text() != text:
                stale.append(str(rel))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if args.check:
        if stale:
            print("stale generated files (run tools/build.py):", *stale, sep="\n  ", file=sys.stderr)
            sys.exit(1)
        print(f"{len(files)} generated files up to date")
    else:
        print(f"wrote {len(files)} files")


if __name__ == "__main__":
    main()
