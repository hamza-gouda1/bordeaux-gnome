// Light/dark following, pure part (no gi imports; tests/test_theme_follow.js).
//
// When org.gnome.desktop.interface color-scheme changes (the Dark Style toggle
// in Quick Settings), the desktop switches between the light variant
// (Merlot Day) and the chosen dark one (Bordeaux or Oxblood Noir): shell
// theme, GTK theme, the per-variant preset keys (blur pipelines, aura accent,
// icon/cursor themes when they are ours), the dark wallpaper, the GNOME
// Terminal default profile and ~/.config/gtk-{3,4}.0/gtk.css. The variant
// data comes from variants/<Variant>.json, generated by tools/build.py.
//
// Everything that was not set by Bordeaux GNOME is left alone: most writes
// carry `ifOneOf`, the values Bordeaux itself uses for that key.

export const LIGHT_DEFAULT = 'Merlot-Day';
export const DARK_DEFAULT = 'Bordeaux';

/** Which variant a color-scheme value asks for. Only prefer-dark is dark. */
export function pickVariant(colorScheme, {dark = DARK_DEFAULT, light = LIGHT_DEFAULT} = {}) {
    return colorScheme === 'prefer-dark' ? dark : light;
}

const q = s => `'${s}'`;

/**
 * Settings writes for `doc` (one variant's JSON); `docs` is every variant's.
 *   {schema, key, value: gvariant text, merge?, ifOneOf?: [gvariant text], requireInList?}
 * `ctx.bgDir` is the folder install.sh copies the wallpapers to.
 */
export function buildOps(doc, docs, ctx = {}) {
    const all = docs.length ? docs : [doc];
    const ops = [
        {schema: 'org.gnome.shell.extensions.user-theme', key: 'name', value: q(doc.shellTheme),
            ifOneOf: all.map(d => q(d.shellTheme))},
        {schema: 'org.gnome.desktop.interface', key: 'gtk-theme', value: q(doc.gtkTheme),
            ifOneOf: [...new Set(all.map(d => q(d.gtkTheme)))]},
    ];
    for (const k of doc.keys ?? []) {
        const op = {schema: k.schema, key: k.key, value: k.value, merge: !!k.merge};
        if (k.ifOneOf)
            op.ifOneOf = [...k.ifOneOf];
        ops.push(op);
    }
    if (doc.terminalProfile) {
        ops.push({schema: 'org.gnome.Terminal.ProfilesList', key: 'default', value: q(doc.terminalProfile),
            ifOneOf: (doc.terminalProfiles ?? [doc.terminalProfile]).map(q), requireInList: doc.terminalProfile});
    }
    // The light wallpaper (picture-uri) never changes; the dark one follows the dark variant.
    if (doc.scheme === 'dark' && ctx.bgDir && doc.wallpaper) {
        const uri = f => q(`file://${ctx.bgDir}/${f}`);
        ops.push({schema: 'org.gnome.desktop.background', key: 'picture-uri-dark', value: uri(doc.wallpaper),
            ifOneOf: all.filter(d => d.scheme === 'dark').map(d => uri(d.wallpaper)),
            requireFile: `${ctx.bgDir}/${doc.wallpaper}`});
    }
    return ops;
}

/**
 * GTK user stylesheets: ~/.config/gtk-N.0/gtk.css is replaced by the target
 * variant's only while it is byte-identical to one of the variants
 * install.sh copies there (never a file the user edited). GTK reads it when
 * an app starts, so running apps follow after a restart.
 *
 * read(path) returns the text or null. Returns [{path, contents}].
 */
export function gtkCssOps(doc, docs, {configDir, themesDir}, read) {
    const ops = [];
    for (const v of ['3', '4']) {
        const path = `${configDir}/gtk-${v}.0/gtk.css`;
        const current = read(path);
        const target = read(`${themesDir}/${doc.variant}/gtk-${v}.0/gtk.css`);
        if (current === null || target === null || current === target)
            continue;
        const ours = docs.some(d => read(`${themesDir}/${d.variant}/gtk-${v}.0/gtk.css`) === current);
        if (ours)
            ops.push({path, contents: target});
    }
    return ops;
}

/**
 * Watches color-scheme and the extension's own follow settings and applies
 * the variant once things settle (debounced), never per frame.
 *
 * deps = {iface, own: Gio.Settings, schedule(ms, fn) -> id, cancel(id),
 *         apply(variantName), log(msg), delay?}
 */
export class ThemeFollower {
    constructor(deps) {
        this._d = deps;
        this._ids = [];
        this._pending = null;
        this.applied = [];
    }

    enable() {
        const {iface, own} = this._d;
        this._ids.push([iface, iface.connect('changed::color-scheme', () => this.queue())]);
        for (const key of ['follow-color-scheme', 'dark-variant', 'light-variant'])
            this._ids.push([own, own.connect(`changed::${key}`, () => this.queue())]);
        // Also once at start: the scheme may have changed while the shell was not running.
        this.queue();
    }

    queue() {
        if (this._pending !== null)
            this._d.cancel(this._pending);
        this._pending = this._d.schedule(this._d.delay ?? 250, () => {
            this._pending = null;
            this.run();
        });
    }

    run() {
        const {iface, own} = this._d;
        if (!own.get_boolean('follow-color-scheme'))
            return null;
        const name = pickVariant(iface.get_string('color-scheme'), {
            dark: own.get_string('dark-variant') || DARK_DEFAULT,
            light: own.get_string('light-variant') || LIGHT_DEFAULT,
        });
        try {
            this._d.apply(name);
            this.applied.push(name);
        } catch (e) {
            this._d.log(`could not switch to ${name}: ${e.message}`);
        }
        return name;
    }

    disable() {
        if (this._pending !== null) {
            this._d.cancel(this._pending);
            this._pending = null;
        }
        for (const [obj, id] of this._ids)
            obj.disconnect(id);
        this._ids = [];
    }
}
